function toRaw([title, cuisine, minutes, description, ingredients, tags = '']: Row): RawDish {
  const slug = title
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  return {
    title,
    description,
    recipeUrl: `https://example.com/recipes/${slug}`,
    sourceName: 'Sample Kitchen',
    imageUrl: null,
    cuisine,
    ideaKey: slug,
    tags: tags ? tags.split(',').map((t) => t.trim()) : [],
    totalMinutes: minutes,
    ingredients: ingredients.split(',').map((part) => {
      const [name = '', family = name, role] = part.trim().split('|');
      return { name, family, role: role === 'm' ? 'main' : 'supporting' };
    }),
  };
}

